#!/usr/bin/env bash
set -u

# Tests for scripts/setup/shirabe-pre-commit.sh, the setup script niwa runs in
# each product repository clone on every apply to install shirabe's pre-commit
# hook.
#
# Every case runs the script the way niwa does: executed directly, from the
# clone root, in a throwaway repository under one checked mktemp directory.
# Its PATH is built here: links to the tools the script and the hook use, plus
# a directory holding a link to the shirabe under test, or not. Each case
# asserts the exact stdout, the exit status, an empty stderr unless it says
# otherwise, and the bytes of every file involved before and after.
#
# HOME, GIT_CONFIG_GLOBAL and GIT_CONFIG_NOSYSTEM are pinned, so no case reads
# or writes the caller's repository or global git configuration.
#
# Needs bash, git 2.31 or later, cmp, grep, mktemp, mkfifo, cksum and a built
# shirabe on PATH (CI puts target/release first), or in SHIRABE_BIN when PATH
# has none. No network.
#
# Usage:
#   PATH="$PWD/target/release:$PATH" bash scripts/shirabe-pre-commit_test.sh
#
# Exit codes:
#   0 - every case passed
#   1 - a case failed, or no shirabe or tool to test with

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
SETUP="$REPO_ROOT/scripts/setup/shirabe-pre-commit.sh"

PASS_COUNT=0
FAIL_COUNT=0
SKIP_COUNT=0
pass() { echo "PASS: $1"; PASS_COUNT=$((PASS_COUNT + 1)); }
fail() { echo "FAIL: $1 - $2"; FAIL_COUNT=$((FAIL_COUNT + 1)); }
skip() { echo "SKIP: $1 - $2"; SKIP_COUNT=$((SKIP_COUNT + 1)); }

SHIRABE=$(command -v shirabe 2>/dev/null) || SHIRABE=""
# The bash floor's container puts no shirabe on PATH and passes SHIRABE_BIN.
case "$SHIRABE" in /*) ;; *) SHIRABE="${SHIRABE_BIN:-}" ;; esac
case "$SHIRABE" in
    /*) [ -x "$SHIRABE" ] || SHIRABE="" ;;
    *) SHIRABE="" ;;
esac
if [ -z "$SHIRABE" ]; then
    echo "shirabe-pre-commit_test: no shirabe on PATH (or in SHIRABE_BIN); put target/release first (cargo build --release)" >&2
    exit 1
fi
SHIRABE="$(cd "$(dirname "$SHIRABE")" && pwd -P)/$(basename "$SHIRABE")"

unset GIT_DIR GIT_WORK_TREE GIT_COMMON_DIR GIT_INDEX_FILE GIT_CONFIG_PARAMETERS GIT_CONFIG_COUNT

T=$(mktemp -d "${TMPDIR:-/tmp}/shirabe-pre-commit-test.XXXXXX") || { echo "shirabe-pre-commit_test: mktemp failed" >&2; exit 1; }
T=$(cd -P "$T" && pwd -P) || exit 1
cleanup() {
    case "${T:-}" in
        */shirabe-pre-commit-test.*)
            chmod -R u+w "$T" 2>/dev/null
            rm -rf "$T"
            ;;
    esac
    return 0
}
trap cleanup EXIT

mkdir -p "$T/home" "$T/tmp" || exit 1
export HOME="$T/home"
export TMPDIR="$T/tmp"
export GIT_CONFIG_GLOBAL="$T/gitconfig"
export GIT_CONFIG_NOSYSTEM=1
: > "$GIT_CONFIG_GLOBAL" || exit 1
export GIT_AUTHOR_NAME=test GIT_AUTHOR_EMAIL=test@example.invalid
export GIT_COMMITTER_NAME=test GIT_COMMITTER_EMAIL=test@example.invalid

# The script's PATH: links to what it and the installed hook run, nothing else,
# so no case finds a shirabe installed on the host.
TOOLS="$T/tools"
mkdir -p "$TOOLS" || exit 1
for tool in bash sh env git cmp grep mktemp rm dirname; do
    p=$(command -v "$tool") || { echo "shirabe-pre-commit_test: $tool is required" >&2; exit 1; }
    ln -s "$p" "$TOOLS/$tool" || exit 1
done
BIN="$T/bin"
mkdir -p "$BIN" || exit 1
ln -s "$SHIRABE" "$BIN/shirabe" || exit 1
P_OK="$BIN:$TOOLS"
P_NONE="$TOOLS"

LINE_MISSING="shirabe not on PATH; pre-commit hook not installed (install it with: tsuku install tsukumogami/shirabe)"
LINE_FOREIGN="a pre-commit hook is already present; shirabe pre-commit hook not installed"
LINE_INSTALLED="installed shirabe pre-commit hook"
LINE_REFRESHED="refreshed shirabe pre-commit hook"
line_outside() { echo "hooks directory $1 is not this clone's own hooks directory; shirabe pre-commit hook not installed"; }
HEADER='# shirabe pre-commit hook -- generated by `shirabe install-hooks`.'

# The hook `shirabe install-hooks` writes in a scratch repository: what every
# install and refresh must produce, byte for byte.
git init -q "$T/ref" || exit 1
( cd "$T/ref" && "$SHIRABE" install-hooks >/dev/null ) || { echo "shirabe-pre-commit_test: install-hooks failed in the reference repository" >&2; exit 1; }
REF="$T/ref/.git/hooks/pre-commit"
[ -f "$REF" ] || { echo "shirabe-pre-commit_test: install-hooks wrote no reference hook" >&2; exit 1; }

# -- helpers -------------------------------------------------------------------

CASE=""
PROB=""
MULTI=""
RUNS=0
begin() { CASE=$1; PROB=""; }
problem() { PROB="$PROB${PROB:+; }$*"; }
end() { if [ -z "$PROB" ]; then pass "$CASE"; else fail "$CASE" "$PROB"; fi; }

# repo <name>: a fresh repository with one commit, printing its path.
repo() {
    local r="$T/$1"
    git init -q "$r" && git -C "$r" commit -q --allow-empty -m init && echo "$r"
}

# run <dir> <PATH value> [VAR=value...]: the script, executed directly from
# <dir> with that PATH. Sets RC; stdout and stderr land in $T/out and $T/err.
run() {
    local dir=$1 path=$2
    shift 2
    ( cd "$dir" && env PATH="$path" "$@" "$SETUP" ) >"$T/out" 2>"$T/err"
    RC=$?
    RUNS=$((RUNS + 1))
    [ "$(wc -l < "$T/out" | tr -d ' ')" -le 1 ] || MULTI="$MULTI [$CASE]"
}

# want <exit status> <stdout line, or empty for none> [stderr]: the run's exit
# status and exact stdout bytes; stderr must be empty unless the third
# argument is `stderr`.
want() {
    if [ -n "$2" ]; then printf '%s\n' "$2" > "$T/want"; else : > "$T/want"; fi
    cmp -s "$T/want" "$T/out" || problem "stdout [$(cat "$T/out")]"
    [ "$RC" = "$1" ] || problem "exit $RC, want $1"
    if [ "${3:-}" != stderr ] && [ -s "$T/err" ]; then problem "stderr [$(cat "$T/err")]"; fi
}

# fp <path>...: every entry under each path, with its type, mode and, for a
# regular file, its checksum. A symlink is listed, never followed, and a FIFO
# is never opened.
fp() {
    local p f
    for p in "$@"; do
        if [ ! -e "$p" ] && [ ! -L "$p" ]; then echo "absent $p"; continue; fi
        find "$p" -print | LC_ALL=C sort | while IFS= read -r f; do
            if [ -L "$f" ]; then echo "link $f -> $(readlink "$f")"
            elif [ -p "$f" ]; then echo "fifo $f $(ls -ld "$f" | cut -c1-10)"
            elif [ -d "$f" ]; then echo "dir $f $(ls -ld "$f" | cut -c1-10)"
            elif [ -f "$f" ]; then echo "file $f $(cksum < "$f") $(ls -ld "$f" | cut -c1-10)"
            else echo "other $f"
            fi
        done
    done
}

# keep <file>...: copy each file aside; same <file>... compares each with its
# copy using cmp.
keep() {
    local f n=0
    rm -rf "$T/kept" && mkdir "$T/kept"
    for f in "$@"; do n=$((n + 1)); cp "$f" "$T/kept/$n"; done
}
same() {
    local f n=0
    for f in "$@"; do
        n=$((n + 1))
        cmp -s "$T/kept/$n" "$f" || problem "$f changed"
    done
}

# is_ref <file>: an executable regular file byte-identical to the reference hook.
is_ref() {
    if [ -L "$1" ] || [ ! -f "$1" ]; then problem "$1 is not a regular file"; return; fi
    [ -x "$1" ] || problem "$1 is not executable"
    cmp -s "$REF" "$1" || problem "$1 differs from the hook install-hooks writes"
}

no_hook() { if [ -e "$1" ] || [ -L "$1" ]; then problem "$1 was created"; fi; }

# A stand-in shirabe that records any run of itself.
stub() {
    mkdir -p "$1"
    printf '#!/bin/sh\n: > "%s"\necho stub-ran\n' "$T/stub-ran" > "$1/shirabe"
    chmod +x "$1/shirabe"
}
stub_ran() { if [ -e "$T/stub-ran" ]; then problem "the in-clone shirabe was executed"; rm -f "$T/stub-ran"; fi; }

# -- the script and its file ---------------------------------------------------

begin "the script is executable, starts with the bash shebang and sets errexit, nounset and pipefail"
[ -f "$SETUP" ] && [ -x "$SETUP" ] || problem "not an executable file"
[ "$(sed -n 1p "$SETUP")" = '#!/usr/bin/env bash' ] || problem "first line [$(sed -n 1p "$SETUP")]"
grep -qx 'set -euo pipefail' "$SETUP" || problem "no set -euo pipefail line"
mode=$(git -C "$REPO_ROOT" ls-files -s scripts/setup/shirabe-pre-commit.sh 2>/dev/null | cut -d' ' -f1)
case "$mode" in ""|100755) ;; *) problem "git ls-files -s gives mode $mode" ;; esac
end

begin "scripts/setup/ holds only shirabe-pre-commit.sh"
entries=$(ls -A "$REPO_ROOT/scripts/setup")
[ "$entries" = shirabe-pre-commit.sh ] || problem "it holds [$entries]"
end

begin "the script unsets the relocating git variables before its first git call"
body=$(grep -v '^[[:space:]]*#' "$SETUP")
unset_at=$(printf '%s\n' "$body" | grep -n '^unset GIT_DIR GIT_WORK_TREE GIT_COMMON_DIR GIT_INDEX_FILE$' | cut -d: -f1)
git_at=$(printf '%s\n' "$body" | grep -n 'git ' | head -n 1 | cut -d: -f1)
[ -n "$unset_at" ] && [ -n "$git_at" ] && [ "$unset_at" -lt "$git_at" ] || problem "unset at line [$unset_at], first git at [$git_at]"
end

begin "every install-hooks call runs the resolved \"\$bin\", and no NIWA_ variable is read"
calls=$(printf '%s\n' "$body" | grep 'install-hooks' | grep -v -e "echo " -e '^header=')
bad=$(printf '%s\n' "$calls" | grep -v '"\$bin" install-hooks')
[ -n "$calls" ] && [ -z "$bad" ] || problem "calls not through \"\$bin\": [$bad]"
if grep -q 'NIWA_' "$SETUP"; then problem "the script names a NIWA_ variable"; fi
end

# -- shirabe missing -----------------------------------------------------------

begin "shirabe not on PATH: the install notice, no pre-commit"
r=$(repo missing)
fp "$r/.git/hooks" > "$T/fp.before"
run "$r" "$P_NONE"
want 0 "$LINE_MISSING"
no_hook "$r/.git/hooks/pre-commit"
fp "$r/.git/hooks" | cmp -s "$T/fp.before" - || problem ".git/hooks changed"
end

begin "shirabe only in an in-clone PATH directory: the install notice, the in-clone shirabe never runs"
r=$(repo inclone)
stub "$r/tools"
run "$r" "$r/tools:$P_NONE"
want 0 "$LINE_MISSING"
no_hook "$r/.git/hooks/pre-commit"
stub_ran
end

begin "shirabe only through an empty PATH entry: the install notice, the in-clone shirabe never runs"
r=$(repo emptyentry)
stub "$r"
run "$r" ":$P_NONE"
want 0 "$LINE_MISSING"
no_hook "$r/.git/hooks/pre-commit"
stub_ran
end

begin "shirabe only through a relative PATH entry: the install notice, the in-clone shirabe never runs"
r=$(repo relentry)
stub "$r/tools"
run "$r" "tools:$P_NONE"
want 0 "$LINE_MISSING"
no_hook "$r/.git/hooks/pre-commit"
stub_ran
end

# -- a hooks directory that is not the clone's own -----------------------------

mkdir -p "$T/shared-hooks" && echo keep > "$T/shared-hooks/README"

begin "absolute core.hooksPath outside the clone (global config): the outside notice, nothing written"
r=$(repo globalhooks)
printf '[core]\n\thooksPath = %s\n' "$T/shared-hooks" > "$T/gitconfig-hooks"
fp "$T/shared-hooks" "$r/.git/hooks" > "$T/fp.before"
run "$r" "$P_OK" GIT_CONFIG_GLOBAL="$T/gitconfig-hooks"
want 0 "$(line_outside "$T/shared-hooks")"
fp "$T/shared-hooks" "$r/.git/hooks" | cmp -s "$T/fp.before" - || problem "a hooks directory changed"
end

begin "absolute core.hooksPath outside the clone (local config): the outside notice, nothing written"
r=$(repo localhooks)
git -C "$r" config core.hooksPath "$T/shared-hooks"
fp "$T/shared-hooks" "$r/.git/hooks" > "$T/fp.before"
run "$r" "$P_OK"
want 0 "$(line_outside "$T/shared-hooks")"
fp "$T/shared-hooks" "$r/.git/hooks" | cmp -s "$T/fp.before" - || problem "a hooks directory changed"
end

begin "in-tree core.hooksPath (.githooks): the outside notice naming it, nothing written"
r=$(repo intree)
mkdir "$r/.githooks" && echo keep > "$r/.githooks/README"
git -C "$r" config core.hooksPath .githooks
fp "$r/.githooks" "$r/.git/hooks" > "$T/fp.before"
run "$r" "$P_OK"
want 0 "$(line_outside "$r/.githooks")"
fp "$r/.githooks" "$r/.git/hooks" | cmp -s "$T/fp.before" - || problem "a hooks directory changed"
end

begin "symlinked hooks directory: the outside notice, nothing written through the link"
r=$(repo linkedhooks)
mv "$r/.git/hooks" "$T/linked-hooks-target"
ln -s "$T/linked-hooks-target" "$r/.git/hooks"
fp "$r/.git/hooks" "$T/linked-hooks-target" > "$T/fp.before"
# git names the directory at the link's target (or, on some versions, at the
# link itself); either way it is the directory the notice must name.
resolved=$(git -C "$r" rev-parse --path-format=absolute --git-path hooks)
case "$resolved" in
    "$T/linked-hooks-target"|"$r/.git/hooks") ;;
    *) problem "git resolves the hooks directory to $resolved" ;;
esac
run "$r" "$P_OK"
want 0 "$(line_outside "$resolved")"
no_hook "$T/linked-hooks-target/pre-commit"
fp "$r/.git/hooks" "$T/linked-hooks-target" | cmp -s "$T/fp.before" - || problem "the link or its target changed"
end

# -- a pre-commit hook shirabe didn't write ------------------------------------

begin "symlinked pre-commit to a tracked file: the foreign notice, link and target unchanged, git status clean"
r=$(repo trackedlink)
mkdir "$r/scripts" && printf '#!/bin/sh\ngofmt -l .\n' > "$r/scripts/pre-commit" && chmod +x "$r/scripts/pre-commit"
git -C "$r" add scripts/pre-commit && git -C "$r" commit -q -m formatter
ln -s ../../scripts/pre-commit "$r/.git/hooks/pre-commit"
keep "$r/scripts/pre-commit"
fp "$r/.git/hooks" "$r/scripts" > "$T/fp.before"
run "$r" "$P_OK"
want 0 "$LINE_FOREIGN"
same "$r/scripts/pre-commit"
fp "$r/.git/hooks" "$r/scripts" | cmp -s "$T/fp.before" - || problem "the link or its target changed"
[ -z "$(git -C "$r" status --porcelain)" ] || problem "git status is not clean"
end

begin "dangling symlink pre-commit: the foreign notice, link unchanged, nothing at its target"
r=$(repo dangling)
ln -s "$T/nowhere/pre-commit" "$r/.git/hooks/pre-commit"
fp "$r/.git/hooks" > "$T/fp.before"
run "$r" "$P_OK"
want 0 "$LINE_FOREIGN"
fp "$r/.git/hooks" | cmp -s "$T/fp.before" - || problem ".git/hooks changed"
if [ -e "$T/nowhere" ]; then problem "something was created at the link's target"; fi
end

begin "symlink to a file holding the shirabe header: the foreign notice, link and target unchanged"
r=$(repo markerlink)
cp "$REF" "$T/marker-target" && printf '# kept by hand\n' >> "$T/marker-target"
ln -s "$T/marker-target" "$r/.git/hooks/pre-commit"
keep "$T/marker-target"
fp "$r/.git/hooks" "$T/marker-target" > "$T/fp.before"
run "$r" "$P_OK"
want 0 "$LINE_FOREIGN"
same "$T/marker-target"
fp "$r/.git/hooks" "$T/marker-target" | cmp -s "$T/fp.before" - || problem "the link or its target changed"
end

# foreign_file <name> <label> <content>: a regular executable pre-commit with
# that content is reported and left byte-unchanged.
foreign_file() {
    begin "$2: the foreign notice, bytes unchanged"
    r=$(repo "$1")
    printf '%s' "$3" > "$r/.git/hooks/pre-commit" && chmod +x "$r/.git/hooks/pre-commit"
    keep "$r/.git/hooks/pre-commit"
    fp "$r/.git/hooks" > "$T/fp.before"
    run "$r" "$P_OK"
    want 0 "$LINE_FOREIGN"
    same "$r/.git/hooks/pre-commit"
    fp "$r/.git/hooks" | cmp -s "$T/fp.before" - || problem ".git/hooks changed"
    end
}

foreign_file plain "regular foreign hook without the header line" \
    "$(printf '#!/bin/sh\necho my own hook\n')"
foreign_file mention "regular hook mentioning shirabe install-hooks without the exact header line" \
    "$(printf '#!/usr/bin/env bash\n# started from shirabe install-hooks, then customized\nexec shirabe validate --format human -- "$@"\n')"
foreign_file edited "regular hook whose header line has extra text" \
    "$(printf '#!/usr/bin/env bash\n%s (edited)\nexit 0\n' "$HEADER")"
foreign_file framework "pre-commit framework hook" \
    "$(printf '#!/usr/bin/env bash\n# File generated by pre-commit: https://pre-commit.com\n# ID: 138fd403232d2ddd5efb44317e38bf03\nexec pre-commit hook-impl --config=.pre-commit-config.yaml --hook-type=pre-commit -- "$@"\n')"

begin "pre-commit that is a directory: the foreign notice, nothing read or written"
r=$(repo dirhook)
mkdir "$r/.git/hooks/pre-commit" && echo x > "$r/.git/hooks/pre-commit/inner"
fp "$r/.git/hooks" > "$T/fp.before"
run "$r" "$P_OK"
want 0 "$LINE_FOREIGN"
fp "$r/.git/hooks" | cmp -s "$T/fp.before" - || problem ".git/hooks changed"
end

begin "pre-commit that is a FIFO: the foreign notice, nothing read or written"
r=$(repo fifohook)
mkfifo "$r/.git/hooks/pre-commit"
fp "$r/.git/hooks" > "$T/fp.before"
# A script that opened the FIFO would block; give it 20 seconds, then release
# and stop it.
( cd "$r" && env PATH="$P_OK" "$SETUP" ) >"$T/out" 2>"$T/err" &
pid=$!
i=0
while kill -0 "$pid" 2>/dev/null && [ "$i" -lt 100 ]; do sleep 0.2; i=$((i + 1)); done
if kill -0 "$pid" 2>/dev/null; then
    problem "the script blocked on the FIFO"
    kill "$pid" 2>/dev/null
    ( : > "$r/.git/hooks/pre-commit" ) &
fi
wait "$pid"
RC=$?
RUNS=$((RUNS + 1))
[ "$(wc -l < "$T/out" | tr -d ' ')" -le 1 ] || MULTI="$MULTI [$CASE]"
want 0 "$LINE_FOREIGN"
fp "$r/.git/hooks" | cmp -s "$T/fp.before" - || problem ".git/hooks changed"
end

# -- install, refresh, current -------------------------------------------------

begin "no hook: installed, executable and byte-identical to install-hooks' output in a scratch repository"
r=$(repo fresh)
run "$r" "$P_OK"
want 0 "$LINE_INSTALLED"
is_ref "$r/.git/hooks/pre-commit"
end

begin "stale shirabe hook: refreshed to the current body"
r=$(repo stale)
printf '#!/usr/bin/env bash\n%s\n# an older body\nexec shirabe validate -- "$@"\n' "$HEADER" > "$r/.git/hooks/pre-commit"
chmod +x "$r/.git/hooks/pre-commit"
run "$r" "$P_OK"
want 0 "$LINE_REFRESHED"
is_ref "$r/.git/hooks/pre-commit"
end

begin "current shirabe hook: two runs print nothing, bytes and mtime unchanged"
r=$(repo current)
( cd "$r" && "$SHIRABE" install-hooks >/dev/null )
hook="$r/.git/hooks/pre-commit"
# An mtime long past: any rewrite moves it to now, past the marker file.
touch -t 202001010000 "$hook" && touch -t 202001010001 "$T/mtime-mark"
keep "$hook"
for n in 1 2; do
    run "$r" "$P_OK"
    want 0 ""
    same "$hook"
    [ -z "$(find "$hook" -newer "$T/mtime-mark")" ] || problem "run $n changed the mtime"
done
is_ref "$hook"
end

# -- the environment and worktrees ---------------------------------------------

begin "inherited GIT_DIR pointing at another repository: that repository untouched, the clone installed"
other=$(repo other)
r=$(repo inherited)
keep "$other/.git/config"
fp "$other/.git/hooks" "$other/.git/config" > "$T/fp.before"
run "$r" "$P_OK" GIT_DIR="$other/.git" GIT_WORK_TREE="$other" GIT_COMMON_DIR="$other/.git" GIT_INDEX_FILE="$other/.git/index"
want 0 "$LINE_INSTALLED"
is_ref "$r/.git/hooks/pre-commit"
same "$other/.git/config"
fp "$other/.git/hooks" "$other/.git/config" | cmp -s "$T/fp.before" - || problem "the other repository changed"
end

design_doc() {
    printf -- '---\nschema: design/v1\nstatus: %s\nproblem: |\n  P.\ndecision: |\n  D.\nrationale: |\n  R.\n---\n\n# DESIGN: hook probe\n\n## Status\n\n%s\n\n' "$1" "$1"
    for s in "Context and Problem Statement" "Decision Drivers" "Considered Options" "Decision Outcome" \
        "Solution Architecture" "Implementation Approach" "Security Considerations" "Consequences"; do
        printf '## %s\n\nContent for %s.\n\n' "$s" "$s"
    done
}

begin "linked worktree: one install into the common hooks, and the hook gates commits there"
r=$(repo shared)
wt="$T/shared-wt"
git -C "$r" worktree add -q "$wt" 2>/dev/null || problem "git worktree add failed"
wtgit=$(git -C "$wt" rev-parse --path-format=absolute --git-dir)
run "$wt" "$P_OK"
want 0 "$LINE_INSTALLED"
is_ref "$r/.git/hooks/pre-commit"
if [ -e "$wtgit/hooks" ] || [ -L "$wtgit/hooks" ]; then problem "a hooks entry was created under $wtgit"; fi
mkdir -p "$wt/docs/designs"
design_doc Proposed > "$wt/docs/designs/DESIGN-hook-probe.md"
git -C "$wt" add docs/designs/DESIGN-hook-probe.md
if ! ( cd "$wt" && PATH="$P_OK" git commit -q -m "valid design" ) >"$T/commit.out" 2>&1; then
    problem "the valid design doc commit was refused: $(cat "$T/commit.out")"
fi
design_doc Bogus > "$wt/docs/designs/DESIGN-hook-bogus.md"
git -C "$wt" add docs/designs/DESIGN-hook-bogus.md
before=$(git -C "$wt" rev-parse HEAD)
if ( cd "$wt" && PATH="$P_OK" git commit -q -m "bogus design" ) >"$T/commit.out" 2>&1; then
    problem "the status: Bogus commit was accepted"
fi
grep -q 'Bogus' "$T/commit.out" || problem "the refusal does not name the bad status: $(cat "$T/commit.out")"
[ "$(git -C "$wt" rev-parse HEAD)" = "$before" ] || problem "HEAD moved after the refused commit"
end

# -- an install error ----------------------------------------------------------

begin "install error with a read-only hooks directory: non-zero exit, install-hooks' stderr, no stdout"
if [ "$(id -u)" = 0 ]; then
    skip "$CASE" "running as root, where a read-only directory is still writable"
else
    r=$(repo readonly)
    chmod 0555 "$r/.git/hooks"
    fp "$r/.git/hooks" > "$T/fp.before"
    run "$r" "$P_OK"
    [ "$RC" != 0 ] || problem "exit 0"
    [ ! -s "$T/out" ] || problem "stdout [$(cat "$T/out")]"
    grep -q '^install-hooks: could not write the hook under ' "$T/err" || problem "stderr [$(cat "$T/err")]"
    fp "$r/.git/hooks" | cmp -s "$T/fp.before" - || problem ".git/hooks changed"
    chmod 0755 "$r/.git/hooks"
    end
fi

# -- every run -----------------------------------------------------------------

begin "every run printed at most one line on stdout ($RUNS runs)"
[ -z "$MULTI" ] || problem "more than one line in:$MULTI"
end

echo
echo "shirabe-pre-commit_test: $PASS_COUNT passed, $FAIL_COUNT failed, $SKIP_COUNT skipped"
[ "$FAIL_COUNT" -eq 0 ]
